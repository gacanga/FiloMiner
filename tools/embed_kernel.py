#!/usr/bin/env python3
"""embed_kernel.py - turns gpu/kawpow_kernel.cuh into gpu/kawpow_kernel_src.h
(an array of raw string literals, each under MSVC's 16 KB literal limit)."""
import pathlib
import sys

root = pathlib.Path(__file__).resolve().parent.parent
src = (root / "gpu" / "kawpow_kernel.cuh").read_text().replace("\r\n", "\n")
lines = src.split("\n")
parts, cur = [], ""
for ln in lines:
    if len(cur) + len(ln) + 1 > 3000:
        parts.append(cur)
        cur = ""
    cur += ln + "\n"
if cur:
    parts.append(cur)
out = ["// kawpow_kernel_src.h - GENERATED by tools/embed_kernel.py from gpu/kawpow_kernel.cuh, do not edit.",
       "#pragma once", "static const char* const fm_kernel_parts[] = {"]
for p in parts:
    if ")FMK\"" in p:
        sys.exit("delimiter found in kernel source")
    out.append('R"FMK(' + p + ')FMK",')
out.append("nullptr };")
(root / "gpu" / "kawpow_kernel_src.h").write_text("\n".join(out) + "\n")
print(f"{len(parts)} parts, {len(src)} bytes")
